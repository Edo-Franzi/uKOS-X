/*
 * \brief aProcess
 *
 * - P0:  Configure the TFLite
 *		  Every 1000-ms
 *			- Simple 4 layer MLP (2 hidden layers)
 *			- Display the result
 *
 */
namespace {

[[noreturn]]
void	aProcess_0(const void *argument) {
			TfLiteTensor	*input;
			TfLiteTensor	*output;
			uint64_t		time[2];
			uint32_t		random[2], delta = 0;
			float32_t		x, y, result;
	const	float32_t		gain = 2.0f;
	const	char_t			*winner;

	UNUSED(argument);

	#if (defined(CORTEX))
	RegisterDebugLogCallback(debuglog);
	#endif

	while (true) {
		kern_suspendProcess(1000u);
		led_toggle(KLED_1);

// Load the TFLite model

		const tflite::Model *model = tflite::GetModel(NN_model_tflite);
		if (model->version() != TFLITE_SCHEMA_VERSION) {
			(void)dprintf(KSYST, "Error : Model version not compatible\n");
			exit(EXIT_OS_FAILURE);
		}

// Create the resolver operator
// Create the micro interpreter

		tflite::MicroMutableOpResolver<3> resolver;
		RegisterOps(resolver);
		tflite::MicroInterpreter interpreter(model, resolver, tensor_arena, KTENSOR_ARENA_SIZE);

// Allocate for the tensors

		if (interpreter.AllocateTensors() != kTfLiteOk) {
			(void)dprintf(KSYST, "Error: Tensor allocation!\n");
			exit(EXIT_OS_FAILURE);
		}

// Prepare the inputs

		random_read(KRANDOM_SOFT, &random[0], 2u);
		x = (((float32_t)random[0] / (float32_t)(KRAND_MAX)) - 0.5f) * gain;
		y = (((float32_t)random[1] / (float32_t)(KRAND_MAX)) - 0.5f) * gain;

		input  = interpreter.input(0);
		input->data.f[0] = x;
		input->data.f[1] = y;

		kern_readTickCount(&time[0]);
		if (interpreter.Invoke() != kTfLiteOk) {
			(void)dprintf(KSYST, "Error: Excecution!\n");
			exit(EXIT_OS_FAILURE);
		}

		kern_readTickCount(&time[1]);
		delta = (uint32_t)(time[1] - time[0]);

// Display the results
// The output is the probability of the class
// The winner takes all

		output = interpreter.output(0);

										  result = output->data.f[0]; winner = "Class A                ";
		if (output->data.f[1] > result) { result = output->data.f[1]; winner = "Class B                "; }
		if (output->data.f[2] > result) { result = output->data.f[2]; winner = "Class C                "; }
		if (output->data.f[3] > result) { result = output->data.f[3]; winner = "Class D                "; }
		if (output->data.f[4] > result) { result = output->data.f[4]; winner = "Inter-class area       "; }

		if (result < 0.3) {											  winner = "Not well classified    "; }

		(void)dprintf(KSYST, "In-0 %6.3f, In-1 %6.3f, "
							 "result: Out-0 %6.1f%%, Out-1 %6.1f%%, Out-2 %6.1f%%, Out-3 %6.1f%%, Out-4 %6.1f%% "
							 "    %s "
							 "Exec time %" PRIu32" [us]\n", x,
							 								y,
							 								output->data.f[0] * 100,
							 								output->data.f[1] * 100,
							 								output->data.f[2] * 100,
							 								output->data.f[3] * 100,
							 								output->data.f[4] * 100,
							 								winner,
							 								delta);
	}
}
}

/*
 * \brief main
 *
 * - Initialise the used libraries
 * - Launch all the processes
 * - Kill the "main". At this moment only the launched processes are executed
 *
 */
CPP_INTERNAL_SCOPE_BEGIN
MAIN_ENTRY(argc, argv[]) {
	proc_t	*process_0;

// ------------------------------------I-----------------------------------------I--------------I

	STRG_LOC_CONST(aStrIden_0[]) =    "Process_User";
	STRG_LOC_CONST(aStrText_0[]) =    "Process user.                             (c) EFr-2026";

	UNUSED(argc);
	UNUSED(argv);

// Initialise the C++ constructors

	CPP_INIT_ARRAYS;

// Specifications for the processes

// NOLINTBEGIN(misc-const-correctness)
//
	PROCESS_STACKMALLOC(
		0,									// Index
		specification_0,					// Specifications (just use vSpecification_x)
		aStrText_0,							// Info string (nullptr if anonymous)
		KKERN_SZ_STACK_XLIB,				// KSZSTACK_xx Stack size (number of words (machine size). _XL Extra large, _LL Large, _MM Medium, _SS Small)
		aProcess_0,							// Code of the process
		aStrIden_0,							// Identifier (nullptr if anonymous)
		KSYST,								// Default Serial Communication Manager (KDEF0, KURTx, KSYST, ...)
		KKERN_PRIORITY_HIGH_02				// KKERN_PRIORITY_HIGH < Priority < KKERN_PRIORITY_LOW_14. KKERN_PRIORITY_LOW_15 is reserved for the idle process
	);

// NOLINTEND(misc-const-correctness)
//

	if (kern_createProcess(&specification_0, nullptr, &process_0) != KERR_KERN_NOERR) { exit(EXIT_OS_FAILURE); }

	LOG(KINFO_USER, "Application launched");
	return (EXIT_OS_SUCCESS_CLI);
}
